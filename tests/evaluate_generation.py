"""OpenAI Answer Quality Evaluation for FinWiseIQ (KAN-37).

Evaluates generate_answer() in src/model.py directly using formatted dataset
context (via format_context() in src/pipeline.py) and the real OpenAI API.
Saves raw generated answers to docs/generation_evaluation_answers.md so
generation quality (correctness, faithfulness, refusal, usefulness) can be
verified independently of retrieval thresholds.

Run from the repo root:  python -m tests.evaluate_generation
"""
from datetime import date
from pathlib import Path

import pandas as pd

from src.model import GenerationError, generate_answer, get_model_name
from src.pipeline import format_context
from src.retrieval import load_dataset, retrieve_context

ROOT = Path(__file__).resolve().parent.parent
EVAL_PATH = ROOT / "tests" / "evaluation_questions.csv"
OUT_PATH = ROOT / "docs" / "generation_evaluation_answers.md"


def main() -> None:
    ev = pd.read_csv(EVAL_PATH, dtype=str).fillna("")
    dataset = load_dataset().to_dict(orient="records")
    rows_by_id = {r["id"]: r for r in dataset}

    summary, details = [], []
    errors = 0

    for _, t in ev.iterrows():
        tid = t["test_id"]
        qtype = t["type"]
        question = t["question"]
        expected_id = t["expected_dataset_id"]

        print(f"Evaluating generation for {tid}: {question}")

        if qtype == "in_scope" and expected_id in rows_by_id:
            # Supply the verified ground-truth row plus top retrieved context
            retrieved = retrieve_context(question)
            context_rows = [rows_by_id[expected_id]]
            for r in retrieved:
                if r["id"] != expected_id and len(context_rows) < 3:
                    context_rows.append(r)
            context_mode = f"Ground-truth {expected_id} + top matches"
        else:
            # Out-of-scope: test model refusal even when unrelated/tangential rows are passed
            context_rows = retrieve_context(question) or dataset[:2]
            context_mode = "Tangential/fallback context (tests prompt refusal)"

        context_str = format_context(context_rows)
        context_ids = ", ".join(r["id"] for r in context_rows)

        try:
            answer = generate_answer(question, context_str)
            status = "Generated OK"
        except GenerationError as exc:
            answer = f"ERROR: {exc}"
            status = "ERROR"
            errors += 1

        summary.append(
            f"| {tid} | {qtype} | {question} | {context_ids} | {status} |"
        )
        details.append(
            f"### {tid} ({qtype}): {question}\n\n"
            f"**Context provided ({context_mode}):** `{context_ids}`\n\n"
            f"**Expected key points:** {t['expected_answer_key_points']}\n\n"
            f"**Generated answer (`{get_model_name()}`):**\n\n"
            + "\n".join(f"> {line}" if line else ">" for line in answer.splitlines())
            + "\n"
        )

    OUT_PATH.write_text(
        "# OpenAI Answer Quality Evaluation — Raw Outputs (KAN-37)\n\n"
        f"**Date:** {date.today():%d %B %Y}  \n"
        f"**Component evaluated:** `generate_answer()` in `src/model.py` + `SYSTEM_PROMPT` in `src/prompt.py`  \n"
        f"**Model:** `{get_model_name()}`  \n"
        "**Generated by:** `python -m tests.evaluate_generation`\n\n"
        "## Run Summary\n\n"
        "| Test | Type | Question | Context IDs Supplied | Status |\n"
        "|---|---|---|---|---|\n"
        + "\n".join(summary)
        + "\n\n## Generated Responses\n\n"
        + "\n".join(details),
        encoding="utf-8",
    )
    print(f"\nSaved {len(summary)} generation results to {OUT_PATH.relative_to(ROOT)}")
    if errors:
        print(f"WARNING: {errors} question(s) failed.")


if __name__ == "__main__":
    main()
