"""End-to-end evaluation for FinWiseIQ (KAN-40).

Runs every question in tests/evaluation_questions.csv through the full
pipeline (retrieval -> OpenAI generation -> sources) using the REAL
OpenAI API, and saves the answers to docs/end_to_end_answers.md so the
team can judge correctness, faithfulness and usefulness.

Needs a valid OPENAI_API_KEY in .env. Makes about 17 API calls
(questions rejected by the threshold do not call OpenAI).

Run from the repo root:  python -m tests.evaluate_end_to_end
"""
from datetime import date
from pathlib import Path

import pandas as pd

from src.model import get_model_name
from src.pipeline import ERROR_MESSAGE, FALLBACK_MESSAGE, process_question
from src.retrieval import THRESHOLD, TOP_K, retrieve_context

ROOT = Path(__file__).resolve().parent.parent
EVAL_PATH = ROOT / "tests" / "evaluation_questions.csv"
OUT_PATH = ROOT / "docs" / "end_to_end_answers.md"


def retrieval_result(test_type: str, expected: str, kept_ids: list[str]) -> str:
    """Same rules as tests/evaluate_retrieval.py."""
    if test_type == "in_scope":
        if kept_ids[:1] == [expected]:
            return "Rank 1"
        return "Top 3" if expected in kept_ids else "Miss"
    return "Rejected" if not kept_ids else "Passed threshold"


def outcome(answer: str) -> str:
    """Which path the pipeline took."""
    if answer == FALLBACK_MESSAGE:
        return "Fallback (OpenAI not called)"
    if answer == ERROR_MESSAGE:
        return "ERROR - API failed"
    return "Generated answer"


def main() -> None:
    ev = pd.read_csv(EVAL_PATH, dtype=str).fillna("")
    summary, details = [], []
    errors = 0

    for _, t in ev.iterrows():
        print(f"Running {t['test_id']}: {t['question']}")
        kept = retrieve_context(t["question"])
        kept_ids = [r["id"] for r in kept]
        answer = process_question(t["question"])
        path = outcome(answer)
        errors += path.startswith("ERROR")

        expected = t["expected_dataset_id"] or "-"
        retrieved = ", ".join(f"{r['id']} ({r['score']:.3f})" for r in kept) or "none"
        summary.append(
            f"| {t['test_id']} | {t['type']} | {t['question']} | {expected} | "
            f"{retrieved} | {retrieval_result(t['type'], expected, kept_ids)} | {path} |"
        )
        details.append(
            f"### {t['test_id']} ({t['type']}): {t['question']}\n\n"
            f"**Expected key points:** {t['expected_answer_key_points']}\n\n"
            f"**Retrieved:** {retrieved}\n\n"
            f"**FinWiseIQ answer:**\n\n"
            + "\n".join(f"> {line}" if line else ">" for line in answer.splitlines())
            + "\n"
        )

    OUT_PATH.write_text(
        "# End-to-End Answers (KAN-40)\n\n"
        f"**Date:** {date.today():%d %B %Y}  \n"
        f"**Model:** `{get_model_name()}`  \n"
        f"**Settings:** top-k = {TOP_K}, threshold = {THRESHOLD}  \n"
        "**Generated by:** `python -m tests.evaluate_end_to_end`\n\n"
        "Raw answers from the real pipeline. The judged five-dimension table is in "
        "`docs/end_to_end_evaluation.md`.\n\n"
        "## Summary\n\n"
        "| Test | Type | Question | Expected | Retrieved (score) | Retrieval | Pipeline path |\n"
        "|---|---|---|---|---|---|---|\n"
        + "\n".join(summary)
        + "\n\n## Answers\n\n"
        + "\n".join(details),
        encoding="utf-8",
    )
    print(f"\nSaved {len(summary)} results to {OUT_PATH.relative_to(ROOT)}")
    if errors:
        print(f"WARNING: {errors} question(s) hit an API error. Check your key and re-run.")


if __name__ == "__main__":
    main()
